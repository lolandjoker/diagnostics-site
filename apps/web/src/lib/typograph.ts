/**
 * Типографика для текстов, которые пишет админ (разборы, описания экспертов): при показе, а не в базе —
 * админ правит текст как обычно.
 * - Короткие предлоги и союзы не остаются в конце строки: после них неразрывный пробел.
 * - Дефис между словами (« - ») — длинное тире, и перед тире тоже неразрывный пробел.
 */
const NBSP = " ";

/** Слова, которые нельзя оставлять в конце строки. */
const SHORT = "в|во|с|со|к|ко|о|об|обо|у|и|а|но|на|по|за|из|от|до|не|ни|для|без|при|про|над|под|что|как|я|мы|вы|он|она|их|его|её";

// Слово целиком: перед ним начало строки, пробел или открывающая скобка/кавычка (просмотр назад
// не поглощает символ, поэтому в «и в доме» срабатывают оба слова); после — обычный пробел
const SHORT_WORD = new RegExp(`(?<=^|[\\s(«"„])(${SHORT})[ \\t]+`, "gimu");

export function typograph(text: string): string {
  return (
    text
      // « - » и « – » между словами → « — »
      .replace(/(\S)[ \t]+[-–][ \t]+/g, `$1${NBSP}— `)
      .replace(/(\S)[ \t]+—/g, `$1${NBSP}—`)
      // Предлог и следующее слово — вместе
      .replace(SHORT_WORD, `$1${NBSP}`)
  );
}
