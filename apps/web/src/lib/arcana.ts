const defs = (id: string) =>
  `<defs><linearGradient id="${id}" x1="0" y1="0" x2="1" y2="1"><stop offset="0" stop-color="#2a2047"/><stop offset="1" stop-color="#120d22"/></linearGradient></defs>`;
const frame = (id: string) =>
  `${defs(id)}<rect width="200" height="320" rx="14" fill="url(#${id})"/><rect x="10" y="10" width="180" height="300" rx="9" fill="none" stroke="${G}" stroke-width="1.4" opacity=".8"/><rect x="16" y="16" width="168" height="288" rx="6" fill="none" stroke="${G}" stroke-width=".6" opacity=".45"/>`;

/** Только символ карты (без текста) — для картинки в боте, где текст рисуется своим шрифтом. */
export function arcanaSymbolSvg(index: number): string {
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 320">${(SYMBOLS[index] ?? SYMBOLS[0]!)()}</svg>`;
}

/** Лицевая сторона карты целиком (для сайта: номер и название — шрифтом страницы). */
export function arcanaFaceSvg(index: number, uid = `a${index}`): string {
  const c = ARCANA[index] ?? ARCANA[0]!;
  const size = c.name.length > 11 ? 18 : c.name.length > 8 ? 21 : 24;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 320" role="img" aria-label="${c.name}">${frame(uid)}` +
    `<text x="100" y="52" text-anchor="middle" fill="${G}" font-family="Cormorant Garamond, Georgia, serif" font-size="22" letter-spacing="3">${c.n}</text>` +
    `${(SYMBOLS[index] ?? SYMBOLS[0]!)()}` +
    `<text x="100" y="278" text-anchor="middle" fill="#f1d796" font-family="Cormorant Garamond, Georgia, serif" font-size="${size}" font-weight="600">${c.name}</text></svg>`
  );
}

/** Рубашка карты — эмблема Таромбы. */
export function arcanaBackSvg(uid = "back"): string {
  const ticks = Array.from({ length: 12 }, (_, i) => {
    const a = (i * Math.PI) / 6;
    return `<line x1="${(100 + Math.cos(a) * 54).toFixed(1)}" y1="${(160 + Math.sin(a) * 54).toFixed(1)}" x2="${(100 + Math.cos(a) * 61).toFixed(1)}" y2="${(160 + Math.sin(a) * 61).toFixed(1)}" stroke="${G}" stroke-width="1.3"/>`;
  }).join("");
  const dots = [[40, 50], [160, 60], [44, 270], [156, 262], [100, 38], [100, 288]]
    .map(([x, y]) => `<circle cx="${x}" cy="${y}" r="1.8" fill="#fff3d6" opacity=".7"/>`)
    .join("");
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 320" aria-hidden="true">${frame(uid)}` +
    `<circle cx="100" cy="160" r="54" fill="none" stroke="${G}" stroke-width="1.2" opacity=".7"/>` +
    `<circle cx="100" cy="160" r="46" fill="none" stroke="${G}" stroke-width=".6" opacity=".45"/>${ticks}` +
    `<path d="M94 132a30 30 0 1 0 26 44 24 24 0 1 1-26-44Z" fill="${G}"/><path d="M122 138l2 6 6 2-6 2-2 6-2-6-6-2 6-2Z" fill="#fff3d6"/>${dots}</svg>`
  );
}
