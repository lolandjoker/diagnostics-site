const G = "#d9b66f";
const S = `fill="none" stroke="${G}" stroke-width="2.2" stroke-linecap="round" stroke-linejoin="round"`;
const F = `fill="${G}"`;
const ray = (n: number, r1: number, r2: number, cx = 100, cy = 150, off = 0) =>
  Array.from({ length: n }, (_, i) => {
    const a = (i * 2 * Math.PI) / n + off;
    return `<line x1="${(cx + Math.cos(a) * r1).toFixed(1)}" y1="${(cy + Math.sin(a) * r1).toFixed(1)}" x2="${(cx + Math.cos(a) * r2).toFixed(1)}" y2="${(cy + Math.sin(a) * r2).toFixed(1)}" ${S}/>`;
  }).join("");
const star = (cx: number, cy: number, r: number, points = 8, inner = 0.35) => {
  let p = "";
  for (let i = 0; i < points * 2; i++) {
    const rr = i % 2 ? r * inner : r;
    const a = (i * Math.PI) / points - Math.PI / 2;
    p += `${(cx + Math.cos(a) * rr).toFixed(1)},${(cy + Math.sin(a) * rr).toFixed(1)} `;
  }
  return p.trim();
};
/** Знак бесконечности с центром (cx, cy), полуширина a. */
const lemniscate = (cx: number, cy: number, a: number) => {
  const h = a * 0.55;
  return `<path d="M${cx} ${cy}C${cx + a * 0.35} ${cy - h} ${cx + a} ${cy - h} ${cx + a} ${cy}S${cx + a * 0.35} ${cy + h} ${cx} ${cy}S${cx - a} ${cy - h} ${cx - a} ${cy}S${cx - a * 0.35} ${cy + h} ${cx} ${cy}Z" ${S}/>`;
};

