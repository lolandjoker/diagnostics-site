import { typograph } from "./typograph";

const NB = " ";

describe("типографика", () => {
  it("короткие предлоги и союзы — с неразрывным пробелом", () => {
    expect(typograph("Помогу разобраться в отношениях и в работе")).toBe(`Помогу разобраться в${NB}отношениях и${NB}в${NB}работе`);
    expect(typograph("В этом году")).toBe(`В${NB}этом году`);
    expect(typograph("Все переписки")).toBe("Все переписки");
  });

  it("дефис между словами — длинное тире, перед тире — неразрывный пробел", () => {
    expect(typograph("Стаж - 14 лет")).toBe(`Стаж${NB}— 14 лет`);
    expect(typograph("Таро – мой путь")).toBe(`Таро${NB}— мой путь`);
    expect(typograph("Знаю — помогу")).toBe(`Знаю${NB}— помогу`);
    // Дефис внутри слова не трогаем
    expect(typograph("по-настоящему")).toBe("по-настоящему");
  });

  it("переносы строк сохраняются", () => {
    expect(typograph("Первый абзац\n\nВторой абзац")).toBe("Первый абзац\n\nВторой абзац");
  });
});
